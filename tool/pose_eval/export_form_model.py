"""Turn form_model.json into the Dart the app compiles, plus a parity fixture.

  --dart     lib/core/services/form_model/squat_form_model.g.dart — the weights
             as constants, so the app needs no asset loading or ML runtime
  --fixture  test fixture: random side-on poses with the features and
             probabilities Python computes for them. The Dart test recomputes
             both from the raw landmarks and must match, which is what proves
             the port of form_features.py is faithful.

Usage:
    python export_form_model.py form_model.json \
        --dart lib/core/services/form_model/squat_form_model.g.dart \
        --fixture test/fixtures/squat_form_parity.json
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
from form_features import FEATURE_NAMES, features  # noqa: E402


def probabilities(model: dict, x: np.ndarray) -> np.ndarray:
    z = np.array(model["coef"]) @ ((x - np.array(model["mean"])) / np.array(model["scale"])) + np.array(model["intercept"])
    e = np.exp(z - z.max())
    return e / e.sum()


def dart_list(v) -> str:
    return "[" + ", ".join(repr(float(x)) for x in v) + "]"


def write_dart(model: dict, path: Path) -> None:
    if list(model["features"]) != list(FEATURE_NAMES):
        sys.exit("feature order in the model differs from form_features.py")
    t = model.get("trained_on", {})
    coef = ",\n    ".join(dart_list(r) for r in model["coef"])
    path.write_text(f"""// GENERATED by tool/pose_eval/export_form_model.py — do not edit by hand.
// Retrain with train_form_classifier.py and re-export instead.
//
// Multinomial logistic regression, classes {model['classes']},
// trained on {t.get('poses', '?')} poses ({t.get('classes', {})}).

abstract final class SquatFormModel {{
  static const mean = {dart_list(model['mean'])};

  static const scale = {dart_list(model['scale'])};

  static const coef = [
    {coef},
  ];

  static const intercept = {dart_list(model['intercept'])};
}}
""")


# A side-on squat at the bottom, facing +x, in pixels: ear, shoulder, hip,
# knee, ankle, heel, toe (the nose is placed ahead of the ear). The fixture jitters it rather than shipping real
# poses, so no one's skeleton (and nothing from a third-party dataset) ends up
# in the repo — parity is about the arithmetic, which random poses test fine.
TEMPLATE = {7: (520, 250), 11: (500, 300), 23: (450, 520), 25: (600, 560),
            27: (560, 760), 29: (530, 780), 31: (640, 785)}


def random_pose(rng) -> np.ndarray:
    lms = np.zeros((33, 4))
    lms[:, :2] = rng.uniform(300, 700, (33, 2))
    lms[:, 2] = rng.normal(0, 50, 33)
    lms[:, 3] = rng.uniform(0.0, 1.0, 33)
    near = rng.integers(2)  # 0 = left side faces the camera
    for j, (x, y) in TEMPLATE.items():
        for side in (0, 1):
            k = j + side
            lms[k, :2] = (x + rng.normal(0, 45), y + rng.normal(0, 45))
            lms[k, 3] = rng.uniform(0.7, 1.0) if side == near else rng.uniform(0.2, 0.9)
    lms[0, :2] = (lms[7 + near, 0] + rng.uniform(20, 60), lms[7 + near, 1] + rng.normal(0, 10))
    lms[0, 3] = rng.uniform(0.7, 1.0)
    if rng.random() < 0.5:  # facing the other way
        lms[:, 0] = 1000 - lms[:, 0]
    return lms


def write_fixture(model: dict, path: Path, n: int) -> None:
    rng = np.random.default_rng(0)
    cases = []
    while len(cases) < n:
        lms = random_pose(rng)
        x = features(lms)
        if x is None:
            continue
        p = probabilities(model, x)
        cases.append({"landmarks": lms.round(4).tolist(), "features": x.astype(float).round(6).tolist(),
                      "probabilities": p.round(6).tolist()})
    blind = random_pose(rng)
    blind[:, 3] = 0.1  # no side tracked: both must refuse it
    cases.append({"landmarks": blind.round(4).tolist(), "features": None, "probabilities": None})
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps({"features": list(FEATURE_NAMES), "cases": cases}))


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("model", type=Path)
    p.add_argument("--dart", type=Path)
    p.add_argument("--fixture", type=Path)
    p.add_argument("--cases", type=int, default=40)
    args = p.parse_args()
    model = json.loads(args.model.read_text())
    if args.dart:
        write_dart(model, args.dart)
        print(f"wrote {args.dart}")
    if args.fixture:
        write_fixture(model, args.fixture, args.cases)
        print(f"wrote {args.fixture}")


if __name__ == "__main__":
    main()
